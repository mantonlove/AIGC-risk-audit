# ---------------------------------------------------------------- 施加与守卫

import re as _re

_HAS_DIGIT = _re.compile(r"\d")
_NEG = set("不无未没非勿甭莫")


def iter_pairs(cats=None, level="safe"):
    """按长度降序产出可用词对。长词优先，避免短词抢先切断长词。"""
    cats = set(PAIRS_BY_CAT) if not cats else set(cats)
    flat, seen = [], set()
    for c in sorted(cats):
        for a, b in PAIRS_BY_CAT.get(c, ()):
            if a == b or a in seen:
                continue
            seen.add(a)
            flat.append((a, b))
    for a, b in sorted(flat, key=lambda x: -len(x[0])):
        if level == "safe" and a in PLAIN_ONLY:
            continue
        yield a, b


def _blocked(text, i, j, head_extra=None):
    """i..j 是匹配区间（左闭右开）。返回 True 表示这次匹配必须放弃。"""
    if _HAS_DIGIT.search(text[max(0, i - 2): j + 2]):
        return True
    if (i > 0 and text[i - 1] in _NEG) or (j < len(text) and text[j] in _NEG):
        return True
    if j < len(text) and text[j] in BLOCK_TAIL:
        return True
    if i > 0 and text[i - 1] in BLOCK_HEAD:
        return True
    if head_extra and i > 0 and text[i - 1] in head_extra:
        return True
    return False


def apply(text, ratio=None, level="safe", cats=None, max_per_pair=99):
    """施加等义压缩词表，返回 (新文本, 改动处数, 改动字数)。

    匹配一律在**原文**上定位，替换结果不会被再次匹配，因此不存在链式替换
    （不会出现"因此→所以→…"这类二次改写）。
    """
    pairs = list(iter_pairs(cats, level))
    target = len(text) if ratio is None else max(1, int(round(len(text) * ratio)))
    used, picked, chars_changed = [], [], 0
    for a, b in pairs:
        if chars_changed >= target:
            break
        head_extra = BLOCK_HEAD_PAIR.get(a)
        n_pair, start = 0, 0
        while n_pair < max_per_pair:
            i = text.find(a, start)
            if i < 0:
                break
            start = i + 1
            j = i + len(a)
            if any(not (j <= u0 or i >= u1) for u0, u1 in used):
                continue
            if _blocked(text, i, j, head_extra):
                continue
            used.append((i, j))
            picked.append((i, j, b))
            chars_changed += sum(1 for x, y in zip(a, b) if x != y) or abs(len(a) - len(b))
            n_pair += 1
    if not picked:
        return text, 0, 0
    picked.sort()
    out, cur = [], 0
    for i, j, b in picked:
        out.append(text[cur:i])
        out.append(b)
        cur = j
    out.append(text[cur:])
    return "".join(out), len(picked), chars_changed
